package org.apache.oodt.cas.workflow.tasks;

//OODT imports
import org.apache.oodt.cas.workflow.structs.WorkflowTaskInstance;

//JUnit imports
import org.junit.Test;

import static org.junit.Assert.assertTrue;

/**
 * Configuration names a task by its class, so the old name has to keep working.
 *
 * <p>A workflow task is selected by fully qualified class name, in policy
 * written by hand and in task definitions generated by earlier releases. Moving
 * the class out of the examples package would fail those at load time — the one
 * moment an operator has nothing useful to go on, since what surfaces is a null
 * engine rather than a missing class.</p>
 */
public class TestTheOldRedirectorNameStillWorks {

    private static final String OLD =
        "org.apache.oodt.cas.workflow.examples.BranchRedirector";

    @Test
    public void testTheOldNameStillLoads() throws Exception {
        Object task = Class.forName(OLD).getDeclaredConstructor().newInstance();
        assertTrue("configuration naming " + OLD + " would fail at load time",
            task instanceof WorkflowTaskInstance);
    }

    @Test
    public void testItIsTheSameBehaviourNotACopy() throws Exception {
        Object task = Class.forName(OLD).getDeclaredConstructor().newInstance();
        assertTrue("the old name should resolve to the moved class, so there "
            + "is one implementation rather than two that can drift",
            task instanceof BranchRedirector);
    }

    @Test
    public void testItIsMarkedDeprecated() throws Exception {
        assertTrue("the old name should tell a compiler it has moved",
            Class.forName(OLD).isAnnotationPresent(Deprecated.class));
    }
}
